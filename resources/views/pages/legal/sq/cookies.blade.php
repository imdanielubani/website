<h2 id="what">1. Çfarë janë cookies</h2>
<p>Cookies janë skedarë të vegjël teksti që një faqe interneti ruan në pajisjen tuaj. Ato përdoren gjerësisht për t’i bërë faqet të funksionojnë në mënyrë të sigurt dhe efikase.</p>

<h2 id="used">2. Cookies që përdorim</h2>
<p>Aktualisht kjo faqe përdor <strong>vetëm cookies thelbësore</strong>. Ne nuk përdorim cookies reklamuese ose gjurmuese.</p>
<ul>
    <li><strong>Cookie e sesionit</strong>: mban faqen funksionale ndërsa lëvizni nga një faqe në tjetrën, për shembull për të shfaqur mesazhet e konfirmimit të formularëve. Skadon kur mbaron sesioni juaj.</li>
    <li><strong>XSRF-TOKEN</strong>: mbron formularët tanë nga falsifikimi i kërkesave ndërmjet faqeve (cross-site request forgery). Skadon kur mbaron sesioni juaj.</li>
</ul>
<p>Nëse në të ardhmen do të përdorim cookies opsionale analitike, ato do të vendosen vetëm me pëlqimin tuaj nëpërmjet panelit të cilësimeve të cookies, dhe kjo politikë do të përditësohet.</p>

<h2 id="storage">3. Ruajtja lokale</h2>
<p>Zgjedhja juaj për cookies ruhet në hapësirën lokale të shfletuesit (local storage) me çelësin <code>cookie-consent</code>, që të mos ju pyesim sërish në çdo vizitë. Gjatë lëvizjes ndërmjet faqeve, përdoret një shenjë e përkohshme në session storage për të shfaqur kalimet ndërmjet faqeve.</p>

<h2 id="third-party">4. Përmbajtje nga palë të treta</h2>
<p>Harta në faqen tonë të kontaktit ofrohet nga Google Maps dhe ngarkohet vetëm kur zgjidhni ta shfaqni. Pasi të ngarkohet, Google mund të vendosë cookies të veta, të rregulluara nga politika e privatësisë së Google.</p>

<h2 id="manage">5. Menaxhimi i preferencave</h2>
<p>Mund ta ndryshoni zgjedhjen tuaj në çdo kohë duke përdorur butonin më poshtë ose lidhjen “Cilësimet e Cookies” në fund të faqes. Mund t’i fshini ose bllokoni cookies edhe nga cilësimet e shfletuesit; bllokimi i cookies thelbësore mund të pengojë funksionimin e formularëve.</p>
